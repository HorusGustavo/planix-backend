package com.planix.planix.dto;

public class OperadoraResponse {
	
	private Long id;
	
	private String nome;
	
	public OperadoraResponse() {
		
	}

	public Long getId() {
		return id;
	}

	public void setId(Long id) {
		this.id = id;
	}

	public String getNome() {
		return nome;
	}

	public void setNome(String nome) {
		this.nome = nome;
	}
	
	

}




